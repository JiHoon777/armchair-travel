"""Build site/js/landmask.js (APP agent): Natural Earth 110m land (public domain), rasterised on a
2-degree grid by docs/data/rasterize_land.py, packed as a base64 bitmask for the fallback globe.

python3 -I tools/make_landmask.py
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = json.loads((ROOT / 'docs/data/worldmap_2deg.json').read_text())
cols, rows = src['cols'], src['rows']
bits = bytearray((cols * rows + 7) // 8)
for r, line in enumerate(src['map']):
    for c, ch in enumerate(line):
        if ch == 'l':
            i = r * cols + c
            bits[i >> 3] |= 1 << (i & 7)
b64 = base64.b64encode(bytes(bits)).decode()
out = f"""// Generated by tools/make_landmask.py from docs/data/worldmap_2deg.json.
// Natural Earth 110m land polygons (public domain) on a {src['step']}-degree grid, rows from
// lat {src['lat_top']} down to {src['lat_bot']}, columns from lon -180. Used only by the fallback globe.
export const LAND = {{ step: {src['step']}, latTop: {src['lat_top']}, latBot: {src['lat_bot']}, cols: {cols}, rows: {rows}, bits: '{b64}' }};
export function landBits() {{
  const s = atob(LAND.bits);
  const a = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) a[i] = s.charCodeAt(i);
  return a;
}}
export function isLand(bits, r, c) {{
  const i = r * LAND.cols + c;
  return (bits[i >> 3] >> (i & 7)) & 1;
}}
"""
(ROOT / 'site/js/landmask.js').write_text(out)
print('wrote site/js/landmask.js', len(out), 'bytes')
